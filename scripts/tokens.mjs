// Build src/styles/tokens.css from design/tokens/tokens.json (the single source of truth, step 3.4).
// Output: the --gr-* custom properties (same values as design/tokens/tokens.css) plus a Tailwind 4
// `@theme` block that maps them to Tailwind namespaces, so utilities like `bg-surface` and
// `text-fg-secondary` read the token variables at runtime (reduced motion overrides still apply).
//
// Usage: node scripts/tokens.mjs           writes the file
//        node scripts/tokens.mjs --check   exits 1 if the committed file is out of date (CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { flatten, resolveAll, toCss } from "../design/tokens/lib.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "design", "tokens", "tokens.json");
const target = join(root, "src", "styles", "tokens.css");

const tokens = flatten(JSON.parse(readFileSync(source, "utf8")));
const resolved = resolveAll(tokens);

const declarations = new Map();
for (const [path, t] of resolved) {
  for (const [name, value] of toCss(path, t.type, t.resolved)) declarations.set(name, value);
}
const reduced = [...resolved]
  .filter(([, t]) => t.extensions?.["app.grooverift.reducedMotion"] !== undefined)
  .flatMap(([path, t]) => toCss(path, t.type, t.extensions["app.grooverift.reducedMotion"]));

// ---- Tailwind theme names ----
// Colour paths are shortened so utilities read naturally: `bg-canvas`, `text-fg`, `border-border-subtle`.
const COLOR_RENAMES = [
  [/^ember\./, ""],
  [/^bg\./, ""],
  [/^text\.on-accent$/, "on-accent"],
  [/^text\.link$/, "link"],
  [/^text\.primary$/, "fg"],
  [/^text\./, "fg-"],
  [/^action\.primary$/, "action"],
  [/^action\.primary-/, "action-"],
  [/^action\.secondary$/, "action-secondary"],
  [/^state\./, ""],
  [/^black\.alpha\./, "black-alpha-"],
];
const colorName = (path) => {
  let p = path.replace(/^color\./, "");
  for (const [re, to] of COLOR_RENAMES) {
    if (re.test(p)) {
      p = p.replace(re, to);
      break;
    }
  }
  return `--color-${p.replace(/\./g, "-")}`;
};

const theme = [];
const themeInline = [];
const cssVar = (path) => `var(--gr-${path.replace(/\./g, "-")})`;
for (const [path, t] of resolved) {
  const v = t.resolved;
  if (path.startsWith("color.")) themeInline.push([colorName(path), cssVar(path)]);
  else if (path === "gradient.brand") themeInline.push(["--background-image-brand", cssVar(path)]);
  else if (path.startsWith("font.family."))
    themeInline.push([`--font-${path.slice("font.family.".length)}`, cssVar(path)]);
  else if (path.startsWith("font.size."))
    themeInline.push([`--text-${path.slice("font.size.".length)}`, cssVar(path)]);
  else if (path.startsWith("font.line-height."))
    themeInline.push([`--leading-${path.slice("font.line-height.".length)}`, cssVar(path)]);
  else if (path.startsWith("font.letter-spacing."))
    themeInline.push([`--tracking-${path.slice("font.letter-spacing.".length)}`, cssVar(path)]);
  else if (path.startsWith("radius."))
    themeInline.push([`--radius-${path.slice("radius.".length)}`, cssVar(path)]);
  else if (path.startsWith("shadow."))
    themeInline.push([`--shadow-${path.slice("shadow.".length)}`, cssVar(path)]);
  else if (path.startsWith("motion.easing."))
    themeInline.push([`--ease-${path.slice("motion.easing.".length)}`, cssVar(path)]);
  else if (path.startsWith("breakpoint."))
    // Media queries cannot read custom properties, so breakpoints are literal.
    theme.push([`--breakpoint-${path.slice("breakpoint.".length)}`, v]);
}

const header = `/* GENERATED by scripts/tokens.mjs from design/tokens/tokens.json. Do not edit by hand.
   Run \`npm run tokens\` after changing the tokens; CI checks that this file is current. */
`;
let css = header + ":root {\n";
for (const [name, value] of declarations) css += `  ${name}: ${value};\n`;
css += "}\n\n@media (prefers-reduced-motion: reduce) {\n  :root {\n";
for (const [name, value] of reduced) css += `    ${name}: ${value};\n`;
css += "  }\n}\n\n";
css +=
  "/* Tailwind 4 theme. Default palette and fonts are cleared: only the Ember tokens exist. */\n";
css +=
  "@theme {\n  --color-*: initial;\n  --font-*: initial;\n  --shadow-*: initial;\n  --radius-*: initial;\n  --text-*: initial;\n  --breakpoint-*: initial;\n";
for (const [name, value] of theme) css += `  ${name}: ${value};\n`;
css += "}\n\n@theme inline {\n";
for (const [name, value] of themeInline) css += `  ${name}: ${value};\n`;
css += "  --default-font-family: var(--gr-font-family-body);\n";
css +=
  "  --breakpoint-sm: initial;\n  --breakpoint-md: initial;\n  --breakpoint-lg: initial;\n  --breakpoint-xl: initial;\n  --breakpoint-2xl: initial;\n";
css += "}\n";

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== css) {
    console.error(`tokens.css is out of date: run \`npm run tokens\` and commit ${target}`);
    process.exit(1);
  }
  console.log(
    `tokens.css is current (${declarations.size} variables, ${themeInline.length + theme.length} theme entries)`,
  );
} else {
  writeFileSync(target, css);
  console.log(
    `tokens.css: ${declarations.size} variables, ${themeInline.length + theme.length} theme entries`,
  );
}
