// Build design/tokens/tokens.css from tokens.json (resolved values, --gr-* names).
// While the step 3.4 decision is open it also writes design/prototypes/tokens/options.css,
// which scopes each option's changed variables under [data-tqN="option"].
// Usage: node design/tokens/build.mjs
import { writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { here, readJson, flatten, withOverrides, resolveAll, toCss } from './lib.mjs';

const tokens = flatten(readJson('tokens.json'));

const declarations = map => {
  const out = new Map();
  for (const [path, t] of map) for (const [name, value] of toCss(path, t.type, t.resolved)) out.set(name, value);
  return out;
};

const base = resolveAll(tokens);
const baseDecl = declarations(base);

const reduced = [...base]
  .filter(([, t]) => t.extensions?.['app.grooverift.reducedMotion'] !== undefined)
  .flatMap(([path, t]) => toCss(path, t.type, t.extensions['app.grooverift.reducedMotion']));

const header = '/* GENERATED by design/tokens/build.mjs from tokens.json. Do not edit by hand. */\n';
let css = header + ':root {\n';
for (const [name, value] of baseDecl) css += `  ${name}: ${value};\n`;
css += '}\n\n@media (prefers-reduced-motion: reduce) {\n  :root {\n';
for (const [name, value] of reduced) css += `    ${name}: ${value};\n`;
css += '  }\n}\n';
writeFileSync(join(here, 'tokens.css'), css);
console.log(`tokens.css: ${baseDecl.size} variables, ${reduced.length} reduced-motion overrides`);

// Decision-time option CSS (only while options.json exists).
const optionsPath = join(here, 'options.json');
if (existsSync(optionsPath)) {
  const options = readJson('options.json');
  let out = header.replace('tokens.json', 'tokens.json + options.json (step 3.4 decision specimens)');
  let count = 0;
  for (const [q, def] of Object.entries(options)) {
    if (q.startsWith('$')) continue;
    for (const [key, opt] of Object.entries(def.options)) {
      const decl = declarations(resolveAll(withOverrides(tokens, opt.overrides)));
      const changed = [...decl].filter(([name, value]) => baseDecl.get(name) !== value);
      out += `[data-${q}="${key}"] {${changed.length ? '\n' : ''}`;
      for (const [name, value] of changed) out += `  ${name}: ${value};\n`;
      out += '}\n';
      count++;
    }
  }
  const dir = join(here, '..', 'prototypes', 'tokens');
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'options.css'), out);
  console.log(`prototypes/tokens/options.css: ${count} option scopes`);
}
